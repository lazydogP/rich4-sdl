const Rich4CharacterSpeech *rich4_character_shop_gift_speech(
    int character, int shop_price, int variant)
{
    int index;
    if (character < 0 || character >= 12 || shop_price <= 0) return 0;
    if (shop_price <= 50)
        index = 2;
    else if (shop_price <= 100)
        index = variant & 1;
    else
        index = 0;
    return &reward_speech[character][index];
}

