const Rich4CharacterSpeech *rich4_character_property_speech(
    int character, Rich4PropertySpeechKind kind)
{
    if (character < 0 || character >= 12 || kind < 0 ||
        kind >= RICH4_PROPERTY_SPEECH_COUNT) return 0;
    if (kind == RICH4_PROPERTY_SPEECH_MAX_LEVEL)
        return &property_max_level_speech[character];
    return &property_speech[character][kind];
}

