#include <string.h>

int rich4_character_speech_snapshot_capture_text(
    Rich4CharacterSpeechSnapshot *snapshot, const char *big5)
{
    size_t length;
    if (snapshot == NULL) return 0;
    memset(snapshot, 0, sizeof(*snapshot));
    snapshot->speaking_resource = -1;
    if (big5 == NULL) return 1;
    length = 0;
    while (length < RICH4_CHARACTER_SPEECH_TEXT_CAPACITY && big5[length] != '\0')
        length++;
    if (length >= RICH4_CHARACTER_SPEECH_TEXT_CAPACITY) return 0;
    memcpy(snapshot->big5, big5, length + 1);
    snapshot->valid = 1;
    return 1;
}

int rich4_character_speech_snapshot_capture(
    Rich4CharacterSpeechSnapshot *snapshot,
    const Rich4CharacterSpeech *speech)
{
    if (snapshot == NULL) return 0;
    if (speech == NULL) {
        rich4_character_speech_snapshot_clear(snapshot);
        return 1;
    }
    if (!rich4_character_speech_snapshot_capture_text(snapshot, speech->big5))
        return 0;
    snapshot->speaking_resource = speech->speaking_resource;
    return snapshot->valid;
}

int rich4_character_speech_snapshot_is_valid(
    const Rich4CharacterSpeechSnapshot *snapshot)
{
    return snapshot != NULL && snapshot->valid == 1 &&
        memchr(snapshot->big5, '\0', sizeof(snapshot->big5)) != NULL;
}

int rich4_character_speech_snapshot_restore(
    const Rich4CharacterSpeechSnapshot *snapshot,
    Rich4CharacterSpeech *storage)
{
    if (storage == NULL || !rich4_character_speech_snapshot_is_valid(snapshot))
        return 0;
    storage->speaking_resource = snapshot->speaking_resource;
    storage->big5 = snapshot->big5;
    return 1;
}

void rich4_character_speech_snapshot_clear(
    Rich4CharacterSpeechSnapshot *snapshot)
{
    if (snapshot == NULL) return;
    memset(snapshot, 0, sizeof(*snapshot));
    snapshot->speaking_resource = -1;
}

