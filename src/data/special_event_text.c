int rich4_special_event_format_names_big5(char *out, size_t out_size,
    const char *marked_template, const char *first_name,
    const char *second_name, int number)
{
    const char *p = marked_template;
    size_t used = 0;
    char decimal[32];
    if (out == NULL || out_size == 0 || p == NULL) return 0;
    out[0] = '\0';
    if (p[0] == '#' && p[1] >= '0' && p[1] <= '9' &&
        p[2] >= '0' && p[2] <= '9' && p[3] >= '0' && p[3] <= '9' &&
        p[4] >= '0' && p[4] <= '9')
        p += 5;
    if (first_name == NULL) first_name = "";
    if (second_name == NULL) second_name = "";
    snprintf(decimal, sizeof(decimal), "%d", number);
    while (*p != '\0') {
        if (p[0] == '%' && p[1] == 's') {
            if (!append_bytes(out, out_size, &used,
                              first_name, strlen(first_name))) return 0;
            first_name = second_name;
            p += 2;
        } else if (p[0] == '%' && p[1] == 'd') {
            if (!append_bytes(out, out_size, &used,
                              decimal, strlen(decimal))) return 0;
            p += 2;
        } else if (p[0] == '%' && p[1] == '%') {
            if (!append_bytes(out, out_size, &used, "%", 1)) return 0;
            p += 2;
        } else {
            if (!append_bytes(out, out_size, &used, p, 1)) return 0;
            p++;
        }
    }
    return 1;
}
