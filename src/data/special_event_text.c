static int append_bytes(char *out, size_t out_size, size_t *used,
                        const char *text, size_t count)
{
    if (*used + count >= out_size) return 0;
    if (count != 0) memcpy(out + *used, text, count);
    *used += count;
    out[*used] = '\0';
    return 1;
}

