int rich4_fortune_portrait_chunk(int physical_id)
{
    /* sub_4562A5 receives character graph +0x18/+0x24/+0x30/+0x3c,
     * which are SDL SPR chunks 1/2/3/4.  Many physical callbacks jump
     * into shared phase-0 tails (notably 13, 16, 18-19 and 22-31). */
    static const signed char chunk[49] = {
         2, 2, 3, 3, 1, 4, 2, 3, 3, 2,
         3, 3, 3, 3, 2, 2, 2, 3, 3, 2,
         1, 4, 4, 2, 3, 4, 3, 1, 4, 4,
         2, 4, 2, 3, 3, 3, 3, 3, 3, 3,
         3, 3, 3, 3, 3, 3, 3, 3, 3
    };
    return physical_id >= 0 && physical_id < 49
        ? (int)chunk[physical_id] : -1;
}

