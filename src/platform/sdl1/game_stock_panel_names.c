const char *game_stock_name_for_state(
    const GameState *state, int stock)
{
    int map;
    if (state == NULL || stock < 0 || stock >= GAME_STOCK_COUNT) return "";
    map = state->stage * GAME_MAPS_PER_STAGE + state->map;
    if (map < 0 || map >= GAME_BACKGROUND_COUNT) map = 0;
    return game_stock_name_table[map * GAME_STOCK_COUNT + stock];
}

int game_stock_panel_map_index(const NewGameSettings *settings)
{
    int index = settings != NULL
        ? settings->stage * GAME_MAPS_PER_STAGE + settings->map : 0;
    return index >= 0 && index < GAME_BACKGROUND_COUNT ? index : 0;
}

const char *game_stock_panel_name(const NewGameSettings *settings, int stock)
{
    int map = game_stock_panel_map_index(settings);
    if (stock < 0 || stock >= GAME_STOCK_COUNT) return "";
    return game_stock_name_table[map * GAME_STOCK_COUNT + stock];
}
