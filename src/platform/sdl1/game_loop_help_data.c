int help_item_label_index(int category, int item)
{
    if (category < 0 || category >= HELP_CATEGORY_COUNT ||
        item < 0 || item >= help_category_item_count[category])
        return 0;
    if (category < 4)
        return help_category_item_offset[category] + item;
    if (category == 4) {
        if (item == 2)
            return 9; /* "card", shared with game-command item 2 */
        return item < 2 ? 22 + item : 21 + item;
    }
    if (category == 5)
        return 37 + item;
    if (category == 6)
        return 55 + item;
    return 85 + item;
}
