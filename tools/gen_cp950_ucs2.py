#!/usr/bin/env python3
"""Emit src/platform/sdl1/text/cp950_ucs2.inc from Python's cp950 codec.

The original binary requests charset 0x88 (CHINESEBIG5_CHARSET = CP950) in
CreateFontA at 0x44FA74. One mapping, no iconv or Win32 fallback.
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "platform" / "sdl1" / "text" / "cp950_ucs2.inc"

LEAD_MIN = 0x81
LEAD_MAX = 0xFE
TRAILS = list(range(0x40, 0x7F)) + list(range(0xA1, 0xFF))
COLS = 16


def ucs2(lead: int, trail: int) -> int:
    try:
        char = bytes((lead, trail)).decode("cp950")
    except UnicodeDecodeError:
        return 0
    code = ord(char)
    if code == 0 or code > 0xFFFF:
        return 0
    return code


def main() -> None:
    values: list[int] = []
    for lead in range(LEAD_MIN, LEAD_MAX + 1):
        for trail in TRAILS:
            values.append(ucs2(lead, trail))

    lines = [
        "/* Generated by tools/gen_cp950_ucs2.py. Do not edit by hand. */",
        "/* CP950: lead 0x81-0xFE, trail 0x40-0x7E then 0xA1-0xFE. 0 = unmapped. */",
        f"static const uint16_t rich4_cp950_ucs2[{len(values)}] = {{",
    ]
    for i in range(0, len(values), COLS):
        chunk = values[i : i + COLS]
        body = ", ".join(f"0x{v:04x}" for v in chunk)
        suffix = "," if i + COLS < len(values) else ""
        lines.append(f"    {body}{suffix}")
    lines.append("};")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="ascii")
    mapped = sum(1 for v in values if v != 0)
    print(f"wrote {OUT} ({len(values)} slots, {mapped} mapped)")


if __name__ == "__main__":
    main()
